import type { DraftRecommendationContext } from './action-registry-schema.js'

const CONTEXT_MARKER = 'DRAFT_CONTINUATION_CONTEXT'
const CONTEXT_LIMIT = 16_000

function retained(markdown: string): DraftRecommendationContext {
  const value = markdown.trim()
  if (!value) return { kind: 'none' }
  if (value.length > CONTEXT_LIMIT) throw new Error(`Draft continuation context exceeds ${CONTEXT_LIMIT} characters`)
  return { kind: 'retained', markdown: value }
}

/** Keep structured draft context in the producer payload without publishing a second recommendation menu. */
export function draftRecommendationContextMarker(markdown: string): string {
  const context = retained(markdown)
  if (context.kind === 'none') return ''
  return `<!-- ${CONTEXT_MARKER}:${Buffer.from(context.markdown, 'utf8').toString('base64url')} -->`
}

function decodeMarker(value: string): string {
  const decoded = Buffer.from(value, 'base64url').toString('utf8')
  if (Buffer.from(decoded, 'utf8').toString('base64url') !== value) throw new Error('Draft continuation context marker is invalid')
  return decoded
}

function withoutRange(markdown: string, start: number, end: number): string {
  return `${markdown.slice(0, start).trimEnd()}\n\n${markdown.slice(end).trimStart()}`.trimEnd()
}

/**
 * Remove transient producer context from reader prose and bind it to the action-review snapshot.
 * Historical articles are unchanged because this runs only at a new review boundary.
 */
export function extractDraftRecommendationContext(markdown: string, prior?: DraftRecommendationContext): { markdown: string; context: DraftRecommendationContext } {
  const markerPattern = new RegExp(`^<!-- ${CONTEXT_MARKER}:([A-Za-z0-9_-]+) -->\\s*$`, 'gm')
  const markers = [...markdown.matchAll(markerPattern)]
  const headings = [...markdown.matchAll(/^## (?:What['’]s next|Next actions)\s*$/gm)]
  if (markers.length > 1 || headings.length > 1 || (markers.length && headings.length)) throw new Error('Article contains multiple draft continuation contexts')

  if (markers[0]?.index !== undefined) {
    const match = markers[0]
    const context = retained(decodeMarker(match[1]))
    return { markdown: withoutRange(markdown, match.index, match.index + match[0].length), context }
  }

  const heading = headings[0]
  if (heading?.index !== undefined) {
    const bodyStart = heading.index + heading[0].length
    const tail = markdown.slice(bodyStart)
    const nextHeading = tail.search(/\n## [^\n]+/)
    const footer = tail.search(/\n---\n(?=\n?\*Generated by \[daily-logger\])/)
    const boundaries = [nextHeading, footer].filter(index => index >= 0)
    const bodyEnd = bodyStart + (boundaries.length ? Math.min(...boundaries) : tail.length)
    return {
      markdown: withoutRange(markdown, heading.index, bodyEnd),
      context: retained(markdown.slice(bodyStart, bodyEnd)),
    }
  }

  return { markdown, context: prior ?? { kind: 'none' } }
}
