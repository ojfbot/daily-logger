import { describe, expect, expectTypeOf, it } from 'vitest'
import { toMarkdown, type GeneratedArticle } from '@ojfbot/daily-logger-journal/article-markdown'
import * as provenance from '@ojfbot/daily-logger-journal/article-provenance'
import { toMarkdown as legacyMarkdown } from '../generate-article.js'
import * as legacyProvenance from '../run-provenance.js'
import type { GeneratedArticle as LegacyArticle } from '../types.js'

const article = {
  title: 'A "quoted" change', date: '2026-11-19', tags: ['journal'],
  summary: 'Preserve $& literally.', body: '## What shipped\n\nA bounded change.',
  schemaVersion: 2, commitCount: 0, reposActive: ['daily-logger'],
  generationMode: 'stub' as const,
  suggestedActions: [{ command: '/test', description: 'Unreviewed action', repo: 'daily-logger', status: 'open' as const, sourceDate: '2026-11-19' }],
  timeReferences: [{ invented: true }],
}

describe('shared journal serialization boundary', () => {
  it('preserves complete Markdown bytes and the existing compatibility entry points', () => {
    expectTypeOf<GeneratedArticle>().toEqualTypeOf<LegacyArticle>()
    expect(legacyMarkdown).toBe(toMarkdown)
    for (const key of ['RunTimingSchema', 'RunEvidenceSchema', 'AuthoringStageSchema', 'ArticleProvenanceSchema',
      'promptSha256', 'buildArticleProvenance', 'parseArticleProvenance', 'preserveProvenanceFrontmatter',
      'formatArticleFooter', 'appendAuthoringStage'] as const) {
      expect(legacyProvenance[key]).toBe(provenance[key])
    }
    expect(toMarkdown(article)).toBe([
      '---',
      'title: "Wednesday — A \\"quoted\\" change"',
      'date: 2026-11-19',
      'tags: ["journal"]',
      'summary: "Preserve $& literally."',
      'status: "draft"',
      'schemaVersion: 2',
      'commitCount: 0',
      'reposActive: ["daily-logger"]',
      '---', '', '## What shipped', '', 'A bounded change.', '', '---', '',
      '*Generated by [daily-logger](https://github.com/ojfbot/daily-logger).*', '',
    ].join('\n'))
  })

  it('round-trips local provenance without inventing runtime values or service identity', () => {
    const input = {
      run: { kind: 'local' as const, capturedAt: '2026-11-19T00:00:00.000Z' },
      stages: [{ role: 'draft' as const, model: 'synthetic', promptVersion: 'fixture-v1', promptSha256: provenance.promptSha256('synthetic') }],
      nodeVersion: 'v24.11.1',
    }
    expect(provenance.buildArticleProvenance(input)).toBeUndefined()
    const captured = provenance.buildArticleProvenance({ ...input, packageVersion: '0.1.0' })!
    const markdown = toMarkdown({ ...article, provenance: captured })
    const raw = markdown.match(/^provenance: (.+)$/m)![1]
    expect(provenance.parseArticleProvenance(raw)).toEqual(captured)
    expect(provenance.parseArticleProvenance('{')).toBeUndefined()
    expect(provenance.RunEvidenceSchema.safeParse({ kind: 'service', runId: 'unqualified' }).success).toBe(false)
    expect(input.stages).toHaveLength(1)
  })

  it('appends attribution in order, preserving literal replacement text and invalid-input behavior', () => {
    const stage = { role: 'draft' as const, model: 'synthetic', promptVersion: 'fixture-v1', promptSha256: provenance.promptSha256('synthetic') }
    const captured = provenance.buildArticleProvenance({
      run: { kind: 'local', capturedAt: '2026-11-19T00:00:00.000Z' }, stages: [stage],
      nodeVersion: 'v24.11.1', packageVersion: '0.1.0',
    })!
    const markdown = toMarkdown({ ...article, provenance: captured })
    const revision = { ...stage, role: 'revision' as const, model: 'literal $& model' }
    const revised = provenance.appendAuthoringStage(markdown, revision)
    expect(provenance.parseArticleProvenance(revised.match(/^provenance: (.+)$/m)![1])?.authoring).toEqual([stage, revision])
    expect(revised).toContain('Authoring model `literal $& model`')
    expect(revised.match(/Generated by \[daily-logger\]/g)).toHaveLength(1)
    expect(provenance.appendAuthoringStage(markdown, { ...revision, model: '' })).toBe(markdown)
    const malformed = '---\nprovenance: {\n---\nBody';
    expect(provenance.appendAuthoringStage(malformed, revision)).toBe(malformed)
    expect(provenance.appendAuthoringStage('Body', revision)).toBe('Body')
    expect(captured.authoring).toEqual([stage])
  })
})
